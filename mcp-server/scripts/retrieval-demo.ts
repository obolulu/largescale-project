/**
 * Run the three documented retrieval queries through a real MCP transport.
 *
 *     node scripts/retrieval-demo.ts                          # spawns the server over stdio
 *     node scripts/retrieval-demo.ts --url http://host/mcp    # calls a running HTTP server
 *     node scripts/retrieval-demo.ts --write                  # also writes docs/mcp_retrieval_tests.md
 *
 * The written file is the README's evidence for "three distinct MCP retrieval tests".
 */

import { writeFileSync } from "node:fs";
import { EOL } from "node:os";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";

import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { StdioClientTransport } from "@modelcontextprotocol/sdk/client/stdio.js";
import { StreamableHTTPClientTransport } from "@modelcontextprotocol/sdk/client/streamableHttp.js";

import { pyRepr } from "../src/log.ts";
import type { DocumentationSearchResult } from "../src/server.ts";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT = resolve(ROOT, "..", "docs", "mcp_retrieval_tests.md");
const TOOL = "search_billing_documentation";
export const QUERIES = ["extra internet price", "partial payment rules", "late payment penalty"];

const NON_ASCII = /[^\x00-\x7e]/g;

type Result = [query: string, data: DocumentationSearchResult];

/** Python's repr() of a float: shortest round-trip digits, "5.0" for integers, exponent outside 1e-4..1e16. */
export function pyFloat(n: number): string {
  if (!Number.isFinite(n)) return Number.isNaN(n) ? "nan" : n > 0 ? "inf" : "-inf";
  const [mantissa, exp] = n.toExponential().split("e") as [string, string];
  const e = Number(exp);
  const sign = mantissa.startsWith("-") ? "-" : "";
  const digits = mantissa.replace("-", "").replace(".", "");
  if (e < -4 || e >= 16) {
    const m = digits.length > 1 ? `${digits[0]}.${digits.slice(1)}` : digits;
    return `${sign}${m}e${e < 0 ? "-" : "+"}${String(Math.abs(e)).padStart(2, "0")}`;
  }
  if (e < 0) return `${sign}0.${"0".repeat(-e - 1)}${digits}`;
  const whole = digits.slice(0, e + 1).padEnd(e + 1, "0");
  const frac = digits.slice(e + 1) || "0";
  return `${sign}${whole}.${frac}`;
}

/**
 * Python's json.dumps(value, indent=2): non-ASCII escaped as \uXXXX (ensure_ascii)
 * and numbers written as Python floats (the tool result's only number is a float score).
 */
export function pyJsonDumps(value: unknown, indent = 2, level = 0): string {
  const pad = " ".repeat(indent * (level + 1));
  const end = " ".repeat(indent * level);
  if (value === null || value === undefined) return "null";
  if (typeof value === "boolean") return value ? "true" : "false";
  if (typeof value === "number") return pyFloat(value);
  if (typeof value === "string") {
    return JSON.stringify(value).replace(NON_ASCII, (c) => "\\" + "u" + c.charCodeAt(0).toString(16).padStart(4, "0"));
  }
  if (Array.isArray(value)) {
    if (value.length === 0) return "[]";
    return `[\n${value.map((v) => pad + pyJsonDumps(v, indent, level + 1)).join(",\n")}\n${end}]`;
  }
  const entries = Object.entries(value as Record<string, unknown>);
  if (entries.length === 0) return "{}";
  return `{\n${entries.map(([k, v]) => `${pad}${pyJsonDumps(k)}: ${pyJsonDumps(v, indent, level + 1)}`).join(",\n")}\n${end}}`;
}

async function run(url: string | undefined): Promise<Result[]> {
  const transport = url
    ? new StreamableHTTPClientTransport(new URL(url))
    : new StdioClientTransport({ command: process.execPath, args: [join("src", "main.ts")], cwd: ROOT });
  const client = new Client({ name: "retrieval-demo", version: "1.0.0" });
  await client.connect(transport);
  const results: Result[] = [];
  try {
    for (const query of QUERIES) {
      const result = await client.callTool({ name: TOOL, arguments: { query } });
      if (result.isError) {
        process.stderr.write(`tool error for ${pyRepr(query)}: ${JSON.stringify(result.content)}\n`);
        process.exit(1);
      }
      results.push([query, result.structuredContent as DocumentationSearchResult]);
    }
  } finally {
    await client.close();
  }
  return results;
}

export function toMarkdown(results: Result[], transport: string, now = new Date()): string {
  const when = `${now.toISOString().slice(0, 16).replace("T", " ")} UTC`;
  const out = [
    "# MCP retrieval tests",
    "",
    `Generated by \`mcp-server/scripts/retrieval-demo.ts\` on ${when}, calling the \`${TOOL}\` tool over **${transport}**.`,
    "The guide was indexed once at server startup; each query below only searched the prebuilt index.",
    "",
  ];
  results.forEach(([query, data], n) => {
    out.push(`## ${n + 1}. \`${query}\``, "", "| Rank | Section | Score |", "|---|---|---|");
    data.matches.forEach((m, i) => out.push(`| ${i + 1} | ${m.reference} | ${pyFloat(m.score)} |`));
    const top = data.matches[0]!;
    out.push("", `Top excerpt (${top.reference}):`, "", "> " + top.text.replaceAll("\n", "\n> "), "");
    out.push("<details><summary>Raw tool result</summary>", "", "```json", pyJsonDumps(data), "```", "", "</details>", "");
  });
  return out.join("\n");
}

async function main(): Promise<void> {
  const { values } = parseArgs({
    options: {
      url: { type: "string" },
      write: { type: "boolean", default: false },
      help: { type: "boolean", short: "h", default: false },
    },
  });
  if (values.help) {
    process.stdout.write(
      "usage: retrieval-demo [-h] [--url URL] [--write]\n\n" +
        "  --url URL   Streamable HTTP endpoint, e.g. http://localhost:8001/mcp\n" +
        `  --write     write ${relative(resolve(ROOT, ".."), OUTPUT)}\n`,
    );
    return;
  }

  const results = await run(values.url);
  for (const [query, data] of results) {
    console.log(`${pyRepr(query)}: ` + data.matches.map((m) => `${m.reference} (${pyFloat(m.score)})`).join(", "));
  }
  if (values.write) {
    const transport = values.url ? `Streamable HTTP (${values.url})` : "stdio";
    // Python's write_text() uses the platform line ending; keep that.
    writeFileSync(OUTPUT, toMarkdown(results, transport).replaceAll("\n", EOL), "utf-8");
    console.log(`Wrote ${OUTPUT}`);
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main();
}
