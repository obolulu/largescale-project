"""Run the three documented retrieval queries through a real MCP transport.

    python scripts/retrieval_demo.py                          # spawns the server over stdio
    python scripts/retrieval_demo.py --url http://host/mcp    # calls a running HTTP server
    python scripts/retrieval_demo.py --write                  # also writes docs/mcp_retrieval_tests.md

The written file is the README's evidence for "three distinct MCP retrieval tests".
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

import anyio
from mcp import Client, StdioServerParameters

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT.parent / "docs" / "mcp_retrieval_tests.md"
TOOL = "search_billing_documentation"
QUERIES = ["extra internet price", "partial payment rules", "late payment penalty"]


async def run(url: str | None) -> list[tuple[str, dict]]:
    target = url or StdioServerParameters(command=sys.executable, args=["-m", "billing_docs.server"], cwd=str(ROOT))
    results = []
    async with Client(target) as client:
        for query in QUERIES:
            result = await client.call_tool(TOOL, {"query": query})
            if result.is_error:
                raise SystemExit(f"tool error for {query!r}: {result.content}")
            results.append((query, result.structured_content))
    return results


def to_markdown(results: list[tuple[str, dict]], transport: str) -> str:
    when = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    out = [
        "# MCP retrieval tests",
        "",
        f"Generated by `mcp-server/scripts/retrieval_demo.py` on {when}, calling the `{TOOL}` tool over **{transport}**.",
        "The guide was indexed once at server startup; each query below only searched the prebuilt index.",
        "",
    ]
    for n, (query, data) in enumerate(results, 1):
        out += [f"## {n}. `{query}`", "", "| Rank | Section | Score |", "|---|---|---|"]
        out += [f"| {i} | {m['reference']} | {m['score']} |" for i, m in enumerate(data["matches"], 1)]
        top = data["matches"][0]
        out += ["", f"Top excerpt ({top['reference']}):", "", "> " + top["text"].replace("\n", "\n> "), ""]
        out += ["<details><summary>Raw tool result</summary>", "", "```json", json.dumps(data, indent=2), "```", "", "</details>", ""]
    return "\n".join(out)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--url", help="Streamable HTTP endpoint, e.g. http://localhost:8001/mcp")
    parser.add_argument("--write", action="store_true", help=f"write {OUTPUT.relative_to(ROOT.parent)}")
    args = parser.parse_args()

    results = anyio.run(run, args.url)
    for query, data in results:
        print(f"{query!r}: " + ", ".join(f"{m['reference']} ({m['score']})" for m in data["matches"]))
    if args.write:
        transport = f"Streamable HTTP ({args.url})" if args.url else "stdio"
        OUTPUT.write_text(to_markdown(results, transport), encoding="utf-8")
        print(f"Wrote {OUTPUT}")


if __name__ == "__main__":
    main()
